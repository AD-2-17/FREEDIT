// Copies the Freedit ABI from the Foundry build (contracts/out) into a typed TS module.
// Run after `arc-forge build`:  npm run abi
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../contracts/out/Freedit.sol/Freedit.json");
const target = resolve(here, "../src/lib/abi/freedit.ts");

const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/export-abi.mjs from contracts/out/Freedit.sol/Freedit.json. Do not edit.\n` +
    `export const freeditAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`wrote ${abi.length} ABI entries to ${target}`);
